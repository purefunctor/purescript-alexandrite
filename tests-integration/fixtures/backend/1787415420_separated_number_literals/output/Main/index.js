export function matchesSeparatedNumber($number) {
  if ($number === 1005) {
    return true;
  }
  if ($number === 1200) {
    return true;
  }
  if ($number === 1300) {
    return true;
  }
  if ($number === 14) {
    return true;
  }
  if ($number === -15) {
    return true;
  }
  return false;
}
